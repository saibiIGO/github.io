with open("saibiprint.html", "r", encoding="utf-8") as f:
    html = f.read()

# 1. 6手分がカード下端で切れないよう行間を最適化
html = html.replace(
    "margin-top: 4px; padding: 4px 5px; box-sizing: border-box; width: 100%; background: #f8fafc;",
    "margin-top: 3px; padding: 3px 5px; box-sizing: border-box; width: 100%; background: #f8fafc;"
)
html = html.replace(
    "font-size: 11px; line-height: 1.45; letter-spacing: -0.03em;",
    "font-size: 10.5px; line-height: 1.32; letter-spacing: -0.03em;"
)

# 2. 好手も含めて最大6手まで選出するよう変更
s1 = html.find("function getDefaultDiagramComment")
s2 = html.find("function buildCommentEditorInputs")
if s1 != -1 and s2 != -1:
    max6_fn = r'''function getDefaultDiagramComment(game, range) {
    if (!range || !range.start) return "";
    const candidates = new Array();
    const textLines = new Array();
    for (let m = range.start - 1; m < range.end; m++) {
        const mv = game.moves.at(m);
        if (!mv) continue;
        const no = m + 1, side = mv.color === 'B' ? '黒' : '白';
        if (mv.ai) {
            candidates.push({ no, side, ai: mv.ai, lost: mv.ai.pointsLost || 0 });
        } else if (mv.comment && !mv.comment.includes("generated by KaTrain")) {
            const c = mv.comment.replace(/\s+/g, " ").trim();
            if (c) textLines.push(`【${no}手目】${c}`);
        }
    }
    // 良い手（損失1.5目未満）を最大2手＋悪手・疑問手を残り枠分選び、合計MAX6手を手数順に並べる
    const goodMoves = candidates.filter(c => c.lost < 1.5).sort((a, b) => a.lost - b.lost).slice(0, 2);
    const badMoves = candidates.filter(c => c.lost >= 1.5).sort((a, b) => b.lost - a.lost).slice(0, 6 - goodMoves.length);
    const topAi = goodMoves.concat(badMoves).sort((a, b) => a.no - b.no);

    const aiLines = topAi.map(item => {
        const l = item.lost;
        const tag = l >= 5.0 ? "⚠️大悪手" : (l >= 3.0 ? "⚡悪手" : (l >= 1.5 ? "💡疑問手" : (l <= 0.3 ? "✨好手" : "👍好判断")));
        let line = `${item.no}手(${item.side}) ${tag}` + (l >= 1.5 ? `(-${l.toFixed(1)}目)` : "");
        const sub = new Array();
        if (item.ai.winText) sub.push(`勝率:${item.ai.winText.replace(/\s+/g, "")}`);
        if (item.ai.scoreText) sub.push(`目差:${item.ai.scoreText}`);
        if (item.ai.bestText) sub.push(`最善:${item.ai.bestText}`);
        if (sub.length > 0) line += `\n └ ${sub.join(" ")}`;
        return line;
    });
    const res = new Array();
    if (aiLines.length > 0) res.push("🤖【AI解析ハイライト】\n" + aiLines.join("\n"));
    if (textLines.length > 0) res.push(textLines.join("\n"));
    return res.join("\n");
}

'''
    html = html[:s1] + max6_fn + html[s2:]

with open("saibiprint.html", "w", encoding="utf-8") as f:
    f.write(html)

print("✅ 好手（✨好手）も含めて最大6手まで表示するようアップグレードしました！")
