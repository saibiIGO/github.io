with open("saibiprint.html", "r", encoding="utf-8") as f:
    html = f.read()

# 1. CSSにカードと右側欄の高さ制限（A4ページはみ出し防止）を追加
overflow_css = """
        .diagram-card { overflow: hidden; }
        .diagram-side-info { overflow: hidden; display: flex; flex-direction: column; justify-content: flex-start; }
        .ai-comment-box {
            margin-top: 4px; padding: 4px 6px; background: #f8fafc;
            border-left: 3px solid #0d9488; border-radius: 3px;
            font-size: 9.5px; line-height: 1.35; color: #0f172a;
            white-space: pre-wrap; overflow: hidden;
        }
"""
if ".ai-comment-box" not in html and "</style>" in html:
    html = html.replace("</style>", overflow_css + "\n    </style>", 1)

# 2. 1譜あたりのAIコメントを「損失が大きい上位3手」に厳選してスッキリ収める
s1 = html.find("function getDefaultDiagramComment")
s2 = html.find("function buildCommentEditorInputs")
if s1 != -1 and s2 != -1:
    compact_fn = """function getDefaultDiagramComment(game, range) {
    if (!range || !range.start) return "";
    const candidates = new Array();
    const textLines = new Array();
    for (let m = range.start - 1; m < range.end; m++) {
        const mv = game.moves.at(m);
        if (!mv) continue;
        const no = m + 1, side = mv.color === 'B' ? '黒' : '白';
        if (mv.ai) {
            candidates.push({ no, side, ai: mv.ai, lost: mv.ai.pointsLost || 0 });
        } else if (mv.comment && !mv.comment.includes("generated by KaTrain")) {
            const c = mv.comment.replace(/\\s+/g, " ").trim();
            if (c) textLines.push(`【${no}手目】${c}`);
        }
    }
    // 損失が大きい順に最大3手まで厳選（手数順に並べ直し）
    const topAi = candidates.slice().sort((a, b) => b.lost - a.lost).slice(0, 3).sort((a, b) => a.no - b.no);
    const aiLines = topAi.map(item => {
        const l = item.lost;
        const tag = l >= 5.0 ? "⚠️大悪手" : (l >= 3.0 ? "⚡悪手" : (l >= 1.5 ? "💡疑問手" : "📌AI評価"));
        let line = `${item.no}手(${item.side}) ${tag}` + (l >= 1.5 ? `(-${l.toFixed(1)}目)` : "");
        const sub = new Array();
        if (item.ai.winText) sub.push(`勝率:${item.ai.winText}`);
        if (item.ai.scoreText) sub.push(`目差:${item.ai.scoreText}`);
        if (item.ai.bestText) sub.push(`最善:${item.ai.bestText.split(" ")[0]}`);
        if (sub.length > 0) line += `\\n └ ${sub.join(" / ")}`;
        return line;
    });
    const res = new Array();
    if (aiLines.length > 0) res.push("🤖【AI解析ハイライト】\\n" + aiLines.join("\\n"));
    if (textLines.length > 0) res.push(textLines.join("\\n"));
    return res.join("\\n");
}

"""
    html = html[:s1] + compact_fn + html[s2:]

# 3. コメント表示divに ai-comment-box クラスを適用
html = html.replace(
    'style="margin-top:6px;padding:6px 8px;background:#f8fafc;border-left:3px solid #0d9488;border-radius:4px;font-size:10.5px;line-height:1.5;color:#0f172a;white-space:pre-wrap;"',
    'class="ai-comment-box"',
    1
)

with open("saibiprint.html", "w", encoding="utf-8") as f:
    f.write(html)

print("✅ A4ページはみ出し防止 ＆ AI解析コンパクト厳選表示の修正が完了しました！")
